import PDFDocument from 'pdfkit';

// DutyTrace palette. The page stays mostly white; navy/teal are used for headings and rules only.
const C = { navy: '#153B50', teal: '#007F86', text: '#253746', muted: '#64748B', border: '#DCE4EA', soft: '#F4F7FA' };

// The built-in PDF font covers Latin-1 only. Anything else would print as garbage characters,
// which is worse than an obvious marker on an official-looking record, so show '?' instead.
export const pdfSafe = (text) => String(text ?? '').replace(/[^\u0020-\u007E\u00A0-\u00FF]/gu, '?');

const fmt = (opts, tz) => new Intl.DateTimeFormat('en-US', { timeZone: tz, ...opts });
const STATUS_LABEL = {
  draft: 'Draft', submitted: 'Submitted', under_review: 'Under review', approved: 'Approved', needs_correction: 'Needs correction',
};
const SESSION_NOTE = {
  complete: '', in_progress: 'Open session - not counted', missing_time_out: 'Missing time-out - not counted',
  orphan_time_out: 'Time-out without time-in - not counted', needs_review: 'Over maximum length - not counted',
};

/**
 * @param dtr      detail from dtr.service.getDetail (revision.snapshot is rendered)
 * @returns Promise<Buffer> a PDF
 */
export function renderDtrPdf(dtr) {
  const snap = dtr.revision.snapshot;
  const tz = snap.timezone;
  const studentName = pdfSafe(snap.student.fullName);
  const dateTime = fmt({ year: 'numeric', month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' }, tz);
  const timeOnly = fmt({ hour: 'numeric', minute: '2-digit', hour12: true }, tz);
  const dayLabel = (key) => fmt({ weekday: 'short', month: 'short', day: 'numeric' }, 'UTC').format(new Date(`${key}T00:00:00Z`));
  const monthLabel = fmt({ month: 'long', year: 'numeric' }, 'UTC').format(new Date(`${snap.month}-01T00:00:00Z`));
  const hrs = (n) => Number(n).toFixed(2);

  const doc = new PDFDocument({
    size: 'A4', margin: 48, bufferPages: true,
    info: { Title: `DTR ${snap.month} - ${studentName} (provisional)`, Author: 'DutyTrace', Subject: 'Provisional monthly daily time record' },
  });
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));
  const done = new Promise((resolve, reject) => { doc.on('end', () => resolve(Buffer.concat(chunks))); doc.on('error', reject); });

  const left = doc.page.margins.left;
  const width = doc.page.width - left - doc.page.margins.right;
  const bottom = () => doc.page.height - doc.page.margins.bottom - 28;

  // ------------------------------------------------------------ header
  doc.font('Helvetica-Bold').fontSize(18).fillColor(C.navy).text('Daily Time Record', left, 48);
  doc.font('Helvetica').fontSize(10).fillColor(C.teal).text(`Student Assistant duty - ${monthLabel}`);
  doc.moveTo(left, doc.y + 6).lineTo(left + width, doc.y + 6).lineWidth(1.5).strokeColor(C.teal).stroke();
  doc.y += 14;

  // Honest labeling: this is not the institution's official form.
  const noteY = doc.y;
  doc.rect(left, noteY, width, 30).lineWidth(0.75).strokeColor(C.border).fillAndStroke(C.soft, C.border);
  doc.font('Helvetica-Bold').fontSize(8.5).fillColor(C.navy)
    .text('PROVISIONAL TEMPLATE - NOT THE OFFICIAL INSTITUTION DTR FORM', left + 8, noteY + 6, { width: width - 16 });
  doc.font('Helvetica').fontSize(8).fillColor(C.muted)
    .text('Generated by DutyTrace from saved QR attendance. Replace with the official form when your institution provides one.', left + 8, noteY + 17, { width: width - 16 });
  doc.y = noteY + 42;

  // ------------------------------------------------------- info block
  const info = [
    ['Student Assistant', studentName], ['Office', pdfSafe(`${snap.office.name} (${snap.office.code})`)],
    ['Month', monthLabel], ['Time zone', snap.timezone],
    ['DTR status', STATUS_LABEL[dtr.status] ?? dtr.status], ['Revision', `${dtr.revision.number}${dtr.revision.number === dtr.currentRevision ? ' (current)' : ' (superseded)'}`],
    ['Generated', dateTime.format(new Date(snap.generatedAt))], ['Required hours (configured)', hrs(snap.totals.requiredHours)],
  ];
  const colW = width / 2;
  let y = doc.y;
  info.forEach(([label, value], i) => {
    const x = left + (i % 2) * colW;
    if (i % 2 === 0 && i > 0) y += 30;
    doc.font('Helvetica').fontSize(7.5).fillColor(C.muted).text(label.toUpperCase(), x, y, { width: colW - 12 });
    doc.font('Helvetica-Bold').fontSize(10).fillColor(C.text).text(value, x, y + 10, { width: colW - 12 });
  });
  doc.y = y + 38;

  // ------------------------------------------------------------- table
  const cols = [
    { label: 'Date', w: 82 }, { label: 'Time in', w: 66 }, { label: 'Time out', w: 66 },
    { label: 'Hours', w: 52, align: 'right' }, { label: 'Notes', w: width - 82 - 66 - 66 - 52 },
  ];
  const rowH = 20;
  const drawHeader = () => {
    const top = doc.y;
    doc.rect(left, top, width, rowH).fill(C.navy);
    let x = left;
    cols.forEach((c) => {
      doc.font('Helvetica-Bold').fontSize(8.5).fillColor('#FFFFFF').text(c.label, x + 6, top + 6, { width: c.w - 12, align: c.align ?? 'left', lineBreak: false });
      x += c.w;
    });
    doc.y = top + rowH;
  };
  const drawRow = (cells, { bold = false, shade = false } = {}) => {
    if (doc.y + rowH > bottom()) { doc.addPage(); doc.y = doc.page.margins.top; drawHeader(); }
    const top = doc.y;
    if (shade) doc.rect(left, top, width, rowH).fill(C.soft);
    doc.moveTo(left, top + rowH).lineTo(left + width, top + rowH).lineWidth(0.5).strokeColor(C.border).stroke();
    let x = left;
    cells.forEach((cell, i) => {
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(8.5).fillColor(C.text)
        .text(cell ?? '', x + 6, top + 6, { width: cols[i].w - 12, align: cols[i].align ?? 'left', lineBreak: false, ellipsis: true });
      x += cols[i].w;
    });
    doc.y = top + rowH;
  };

  drawHeader();
  let any = false;
  for (const day of snap.days) {
    day.sessions.forEach((s, i) => {
      any = true;
      const note = [SESSION_NOTE[s.status], s.flags?.includes('crosses_midnight') ? 'Crosses midnight' : ''].filter(Boolean).join('; ');
      drawRow([
        i === 0 ? dayLabel(day.date) : '',
        s.timeIn ? timeOnly.format(new Date(s.timeIn)) : '--',
        s.timeOut ? timeOnly.format(new Date(s.timeOut)) : '--',
        s.counted ? hrs(s.seconds / 3600) : '--',
        note,
      ]);
    });
  }
  if (!any) drawRow(['No attendance recorded this month', '', '', '', '']);
  drawRow(['Total', '', '', hrs(snap.totals.recordedHours), 'Recorded hours - counted sessions only'], { bold: true, shade: true });

  // ------------------------------------------------------------ summary
  if (doc.y + 150 > bottom()) { doc.addPage(); doc.y = doc.page.margins.top; }
  doc.y += 16;
  const sy = doc.y;
  const stats = [
    ['Recorded hours', hrs(snap.totals.recordedHours)], ['Required hours', hrs(snap.totals.requiredHours)],
    ['Remaining (recorded)', hrs(snap.totals.remainingHours)], ['Incomplete sessions', String(snap.totals.incompleteCount)],
  ];
  const sw = width / 4;
  stats.forEach(([label, value], i) => {
    const x = left + i * sw;
    doc.rect(x, sy, sw - 6, 44).lineWidth(0.75).strokeColor(C.border).stroke();
    doc.font('Helvetica').fontSize(7.5).fillColor(C.muted).text(label.toUpperCase(), x + 8, sy + 8, { width: sw - 22 });
    doc.font('Helvetica-Bold').fontSize(14).fillColor(C.navy).text(value, x + 8, sy + 22, { width: sw - 22 });
  });
  doc.y = sy + 56;

  // Recorded and verified are different things; verified exists only after approval.
  doc.font('Helvetica-Bold').fontSize(9).fillColor(C.text);
  if (dtr.status === 'approved' && dtr.verifiedRevision === dtr.revision.number) {
    doc.text(`Supervisor-verified hours: ${hrs(dtr.verifiedHours)}`, left, doc.y, { width });
    doc.font('Helvetica').fontSize(8.5).fillColor(C.muted)
      .text(`Approved ${dateTime.format(new Date(dtr.decidedAt))}. Only counted sessions are verified; flagged sessions are not.`, { width });
  } else {
    doc.text('Supervisor-verified hours: not verified', left, doc.y, { width });
    doc.font('Helvetica').fontSize(8.5).fillColor(C.muted)
      .text(dtr.status === 'approved'
        ? 'This revision is not the revision that was approved.'
        : 'Recorded hours are not verified until a supervisor approves this DTR.', { width });
  }
  if (snap.flags.length) {
    doc.y += 8;
    doc.font('Helvetica-Bold').fontSize(9).fillColor(C.text).text('Flagged attendance (not counted)', left, doc.y, { width });
    doc.font('Helvetica').fontSize(8.5).fillColor(C.muted);
    for (const f of snap.flags.slice(0, 25)) doc.text(`${dayLabel(f.date)} - ${f.message}`, { width });
    if (snap.flags.length > 25) doc.text(`...and ${snap.flags.length - 25} more.`, { width });
  }

  // --------------------------------------------------------- signatures
  if (doc.y + 90 > bottom()) { doc.addPage(); doc.y = doc.page.margins.top; }
  const gy = Math.max(doc.y + 34, 0);
  const approver = [...dtr.history].reverse().find((e) => e.action === 'approved');
  [['Student Assistant', studentName], ['Supervisor', dtr.status === 'approved' && approver ? pdfSafe(approver.actor.fullName) : '']].forEach(([role, name], i) => {
    const x = left + i * (width / 2) + (i ? 12 : 0);
    const w = width / 2 - 12;
    doc.moveTo(x, gy).lineTo(x + w, gy).lineWidth(0.75).strokeColor(C.text).stroke();
    doc.font('Helvetica').fontSize(8.5).fillColor(C.text).text(name || ' ', x, gy + 4, { width: w });
    doc.fillColor(C.muted).fontSize(7.5).text(`${role} - signature over printed name`, x, gy + 16, { width: w });
  });

  // ------------------------------------------------------------- footer
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i += 1) {
    doc.switchToPage(i);
    doc.page.margins.bottom = 0; // footer sits inside the bottom margin; stop pdfkit adding a page
    const fy = doc.page.height - 40;
    doc.moveTo(left, fy - 6).lineTo(left + width, fy - 6).lineWidth(0.5).strokeColor(C.border).stroke();
    doc.font('Helvetica').fontSize(7.5).fillColor(C.muted)
      .text(`DutyTrace provisional DTR | ${dtr.id} | revision ${dtr.revision.number}`, left, fy, { width: width - 80, lineBreak: false })
      .text(`Page ${i + 1} of ${range.count}`, left + width - 80, fy, { width: 80, align: 'right', lineBreak: false });
  }

  doc.end();
  return done;
}
