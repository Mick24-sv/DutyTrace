import {test} from 'node:test';
import assert from 'node:assert/strict';
import {loadFixtures,makeClient,query,setupTestServer} from './helpers/testEnv.js';
let fx;
const ctx=setupTestServer({},async()=>{fx=await loadFixtures(api);});
const api=makeClient(ctx);
const as=who=>({cookie:fx.cookies[who]});
test('students update their own name, year and course without changing privileged fields',async()=>{
  const body={fullName:'Updated Student',yearLevel:3,course:'BS Information Technology'};
  assert.equal((await api.request('PATCH','/users/me/profile',{body})).status,401);
  assert.equal((await api.request('PATCH','/users/me/profile',{...as('supervisorA'),body})).status,403);
  assert.equal((await api.request('PATCH','/users/me/profile',{...as('studentA'),body:{...body,role:'admin'}})).status,400);
  assert.equal((await api.request('PATCH','/users/me/profile',{...as('studentA'),body:{...body,yearLevel:99}})).status,400);
  const saved=await api.request('PATCH','/users/me/profile',{...as('studentA'),body});
  assert.equal(saved.status,200,JSON.stringify(saved.body));
  assert.equal(saved.body.data.user.fullName,body.fullName);
  assert.equal(saved.body.data.user.course,body.course);
  assert.equal(saved.body.data.user.yearLevel,3);
  assert.equal(saved.body.data.user.role,'student');
  assert.equal(saved.body.data.user.office.id,fx.officeIds.A);
  const session=await api.get('/auth/me',as('studentA'));
  assert.equal(session.body.data.user.course,body.course);
  const overview=await api.get(`/users/${fx.ids.studentA}/student-overview`,as('admin'));
  assert.equal(overview.body.data.student.yearLevel,3);
  assert.equal((await query('SELECT year_level FROM users WHERE id=$1',[fx.ids.studentA2])).rows[0].year_level,null);
  const cleared=await api.request('PATCH','/users/me/profile',{...as('studentA'),body:{...body,yearLevel:null,course:null}});
  assert.equal(cleared.status,200);
});

test('profile photos accept small raster images and remain private to authorized viewers',async()=>{
  const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j59kAAAAASUVORK5CYII=','base64');
  assert.equal((await api.upload('/users/me/photo',png,{...as('supervisorA'),filename:'profile.png'})).status,403);
  assert.equal((await api.upload('/users/me/photo',Buffer.from('%PDF-1.4'),{...as('studentA'),filename:'profile.pdf'})).status,400);
  const uploaded=await api.upload('/users/me/photo',png,{...as('studentA'),filename:'profile.png'});
  assert.equal(uploaded.status,200);
  const path=`/users/${fx.ids.studentA}/photo`;
  assert.equal((await api.raw('GET',path)).status,401);
  assert.equal((await api.raw('GET',path,as('studentA2'))).status,404);
  assert.equal((await api.raw('GET',path,as('supervisorB'))).status,404);
  const photo=await api.raw('GET',path,as('admin'));
  assert.equal(photo.status,200);
  assert.equal(photo.headers.get('content-type'),'image/png');
  assert.deepEqual(photo.buffer,png);
  const cached=await api.raw('GET',path,{...as('admin'),headers:{'if-none-match':photo.headers.get('etag')}});
  assert.equal(cached.status,304);
  assert.equal(cached.buffer.length,0);
  assert.equal((await api.raw('GET',path,{...as('studentA2'),headers:{'if-none-match':photo.headers.get('etag')}})).status,404);
  const user=(await api.get('/auth/me',as('studentA'))).body.data.user;
  assert.ok(user.photoUrl.includes(`/users/${fx.ids.studentA}/photo`));
  assert.ok(!('profile_photo' in user));
  assert.equal((await api.request('DELETE','/users/me/photo',as('studentA'))).status,200);
  assert.equal((await api.raw('GET',path,as('admin'))).status,404);
});
