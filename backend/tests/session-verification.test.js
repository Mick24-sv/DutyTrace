import { test } from 'node:test';
import assert from 'node:assert/strict';
import { insertEvent,loadFixtures,makeClient,setupTestServer } from './helpers/testEnv.js';
let fx;
const ctx=setupTestServer({},async()=>{fx=await loadFixtures(api);});
const api=makeClient(ctx);
const as=who=>({cookie:fx.cookies[who]});
test('session approval is scoped, idempotent, leaves later attendance pending, and is replaced by DTR approval',async()=>{
  const now=new Date();
  const date=new Date(Date.UTC(now.getUTCFullYear(),now.getUTCMonth()-1,5)).toISOString().slice(0,10);
  const month=date.slice(0,7);
  const endpoint=`/attendance/users/${fx.ids.studentA}`;
  await insertEvent(fx.ids.studentA,fx.officeIds.A,'time_in',`${date}T01:00:00Z`);
  await insertEvent(fx.ids.studentA,fx.officeIds.A,'time_out',`${date}T03:00:00Z`);
  const history=await api.get(`${endpoint}?month=${month}`,as('supervisorA'));
  const session=history.body.data.days[0].sessions[0];
  const input={sessionId:session.id,date,timeIn:session.timeIn,timeOut:session.timeOut,explanation:'Checked the signed office duty log.'};
  assert.equal((await api.post(`${endpoint}/verify-session`,{...as('studentA'),body:input})).status,403);
  assert.equal((await api.post(`${endpoint}/verify-session`,{...as('supervisorB'),body:input})).status,403);
  assert.equal((await api.post(`${endpoint}/verify-session`,{...as('supervisorA'),body:{...input,timeOut:`${date}T04:00:00.000Z`}})).status,409);
  for(let i=0;i<2;i++) assert.equal((await api.post(`${endpoint}/verify-session`,{...as('supervisorA'),body:input})).status,200);
  await insertEvent(fx.ids.studentA,fx.officeIds.A,'time_in',`${date}T06:00:00Z`);
  await insertEvent(fx.ids.studentA,fx.officeIds.A,'time_out',`${date}T07:00:00Z`);
  const updated=await api.get(`${endpoint}?month=${month}`,as('supervisorA'));
  assert.equal(updated.body.data.totals.recordedHours,3);
  assert.equal(updated.body.data.totals.verifiedHours,2);
  assert.equal(updated.body.data.days[0].sessions[1].verified,false);
  const created=await api.post('/dtrs',{...as('studentA'),body:{month}});
  assert.equal(created.status,201,JSON.stringify(created.body));
  const id=created.body.data.id;
  assert.equal((await api.post(`/dtrs/${id}/submit`,as('studentA'))).status,200);
  assert.equal((await api.post(`/dtrs/${id}/start-review`,as('supervisorA'))).status,200);
  assert.equal((await api.post(`/dtrs/${id}/approve`,{...as('supervisorA'),body:{acknowledgeIncomplete:true}})).status,200);
  const final=await api.get(`${endpoint}?month=${month}`,as('supervisorA'));
  assert.equal(final.body.data.totals.verifiedHours,3);
});
