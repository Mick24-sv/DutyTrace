import {test} from 'node:test';
import assert from 'node:assert/strict';
import {insertEvent,loadFixtures,makeClient,query,setupTestServer} from './helpers/testEnv.js';
let fx;
const ctx=setupTestServer({},async()=>{fx=await loadFixtures(api);});
const api=makeClient(ctx);
const as=who=>({cookie:fx.cookies[who]});

test('supervisor notifies the student, corrects the DTR, and verifies the final monthly total with history',async()=>{
  const today=new Date();
  const date=new Date(Date.UTC(today.getUTCFullYear(),today.getUTCMonth()-1,15)).toISOString().slice(0,10);
  const month=date.slice(0,7);
  const termEnd=new Date(Date.UTC(today.getUTCFullYear(),today.getUTCMonth()+2,0)).toISOString().slice(0,10);
  const term=await api.post('/semesters',{...as('admin'),body:{academicYear:'Supervisor summary test',semester:'first',startsOn:`${month}-01`,endsOn:termEnd,completionDeadline:null,timezone:'Asia/Manila'}});
  assert.equal(term.status,201,JSON.stringify(term.body));
  assert.equal((await api.put(`/semesters/${term.body.data.term.id}/requirements/${fx.ids.studentA}`,{...as('admin'),body:{officeId:fx.officeIds.A,requiredHours:210}})).status,200);
  const iso=hour=>`${date}T${hour}:00:00.000Z`;
  await insertEvent(fx.ids.studentA,fx.officeIds.A,'time_in',iso('08'));
  await insertEvent(fx.ids.studentA,fx.officeIds.A,'time_out',iso('10'));
  const created=await api.post('/dtrs',{...as('studentA'),body:{month}});
  assert.equal(created.status,201,JSON.stringify(created.body));
  const id=created.body.data.id;
  assert.equal((await api.post(`/dtrs/${id}/submit`,as('studentA'))).status,200);
  assert.equal((await api.post(`/dtrs/${id}/start-review`,as('supervisorA'))).status,200);
  const final={verifiedHours:54,effectiveDate:date,reason:'Verified the complete paper office log and corrected the monthly total.',acknowledgeIncomplete:true};
  assert.equal((await api.post(`/dtrs/${id}/verify-edited-month`,{...as('supervisorA'),body:final})).body.error.code,'NOTICE_REQUIRED');
  assert.equal((await api.post(`/dtrs/${id}/take-over`,{...as('supervisorB'),body:{reason:'I will review these hours.'}})).status,403);
  const notice=await api.post(`/dtrs/${id}/take-over`,{...as('supervisorA'),body:{reason:'I will check your times against the signed duty log.'}});
  assert.equal(notice.status,200,JSON.stringify(notice.body));
  assert.equal(notice.body.data.supervisorEditing,true);
  const session=notice.body.data.revision.snapshot.days.flatMap(d=>d.sessions)[0];
  const correction={dtrId:id,sessionId:session.id,originalTimeIn:session.timeIn,originalTimeOut:session.timeOut,
    events:[{eventType:'time_in',recordedAt:iso('08')},{eventType:'time_out',recordedAt:iso('12')}],remarks:'Checked the original signed office attendance log.'};
  const blocked=await api.post('/attendance-discrepancies/student-correction',{...as('studentA'),body:correction});
  assert.equal(blocked.body.error.code,'SUPERVISOR_EDITING');
  assert.equal((await api.post('/attendance-discrepancies/supervisor-correction',{...as('supervisorA'),body:{...correction,studentId:fx.ids.studentA}})).status,201);
  const approved=await api.post(`/dtrs/${id}/verify-edited-month`,{...as('supervisorA'),body:final});
  assert.equal(approved.status,200,JSON.stringify(approved.body));
  assert.equal(approved.body.data.verifiedHours,54);
  assert.equal(approved.body.data.revision.snapshot.totals.recordedHours,4);
  assert.equal(approved.body.data.revision.snapshot.supervisorVerification.seconds,54*3600);
  assert.equal(approved.body.data.revisions.length,2);
  const summary=await api.get('/reports/dashboard-stats',as('supervisorA'));
  assert.equal(summary.status,200,JSON.stringify(summary.body));
  const studentSummary=summary.body.data.assistants.find(student=>student.id===fx.ids.studentA);
  assert.equal(studentSummary.monthlyVerifiedHours[month],54);
  assert.equal(studentSummary.monthlyHours[month],4);
  assert.equal(studentSummary.monthlyDtrStatuses[month],'approved');
  assert.equal(studentSummary.semesterVerifiedHours,54);
  assert.equal(studentSummary.recordedHoursLeft,156);
  const original=await api.get(`/dtrs/${id}?revision=1`,as('studentA'));
  assert.equal(original.body.data.revision.snapshot.totals.recordedHours,2);
  assert.equal((await query('SELECT count(*)::int AS n FROM attendance_events WHERE user_id=$1',[fx.ids.studentA])).rows[0].n,2);
  assert.equal((await api.post(`/dtrs/${id}/verify-edited-month`,{...as('supervisorA'),body:final})).status,409);
  assert.ok((await api.get('/notifications',as('studentA'))).body.data.notifications.some(n=>n.type==='dtr_supervisor_editing'));
});
